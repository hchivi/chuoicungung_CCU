// Fallback resolver for search queries to dynamic strategic sponsor
export function resolveStrategicSponsor(query = "", selectedPhase = "all") {
  const cleanQ = query.toLowerCase().trim();

  if (cleanQ) {
    // 1. Quà tặng / Nông sản / FMCG / 2/9 / Mít sấy / Lipton / Màng co
    if (
      cleanQ.includes("quà") || 
      cleanQ.includes("mít") || 
      cleanQ.includes("màng co") || 
      cleanQ.includes("lipton") || 
      cleanQ.includes("chocopie") || 
      cleanQ.includes("2/9") || 
      cleanQ.includes("tết") || 
      cleanQ.includes("fmcg") ||
      cleanQ.includes("nông sản") ||
      cleanQ.includes("hộp quà")
    ) {
      return STRATEGIC_FOUNDING_PARTNERS.find(p => p.id === "fp-tahomart-gift") || STRATEGIC_FOUNDING_PARTNERS[0];
    }

    // 2. Cơ khí / CNC / Khuôn mẫu / Đồ gá
    if (
      cleanQ.includes("cơ khí") || 
      cleanQ.includes("cnc") || 
      cleanQ.includes("khuôn") || 
      cleanQ.includes("chi tiết") || 
      cleanQ.includes("jig") || 
      cleanQ.includes("đột dập") || 
      cleanQ.includes("tiện") || 
      cleanQ.includes("phay")
    ) {
      return STRATEGIC_FOUNDING_PARTNERS.find(p => p.id === "fp-longthanh-me") || STRATEGIC_FOUNDING_PARTNERS[2];
    }

    // 3. Bao bì / Carton / In ấn / Hộp giấy
    if (
      cleanQ.includes("bao bì") || 
      cleanQ.includes("carton") || 
      cleanQ.includes("thùng") || 
      cleanQ.includes("in ấn") || 
      cleanQ.includes("offset") || 
      cleanQ.includes("hộp cứng") ||
      cleanQ.includes("pallet")
    ) {
      return STRATEGIC_FOUNDING_PARTNERS.find(p => p.id === "fp-tanphat-packaging") || STRATEGIC_FOUNDING_PARTNERS[3];
    }

    // 4. Đồng phục / May mặc / PPE / Bảo hộ
    if (
      cleanQ.includes("đồng phục") || 
      cleanQ.includes("áo") || 
      cleanQ.includes("thun") || 
      cleanQ.includes("bảo hộ") || 
      cleanQ.includes("ppe") || 
      cleanQ.includes("nón") || 
      cleanQ.includes("túi vải") ||
      cleanQ.includes("may")
    ) {
      return STRATEGIC_FOUNDING_PARTNERS.find(p => p.id === "fp-chuyengiadongphuc") || STRATEGIC_FOUNDING_PARTNERS[1];
    }
  }

  // Check by phase if no specific query matched
  if (selectedPhase === "5.3" || selectedPhase === "5") {
    return STRATEGIC_FOUNDING_PARTNERS.find(p => p.id === "fp-chuyengiadongphuc");
  }
  if (selectedPhase === "3.1" || selectedPhase === "3") {
    return STRATEGIC_FOUNDING_PARTNERS.find(p => p.id === "fp-longthanh-me");
  }
  if (selectedPhase === "4.1" || selectedPhase === "4") {
    return STRATEGIC_FOUNDING_PARTNERS.find(p => p.id === "fp-tahomart-gift");
  }

  // Default default spotlight
  return STRATEGIC_FOUNDING_PARTNERS[0];
}

