// Matching Algorithm: Match Jobs for Uploaded CV
export function matchJobsForCandidate(cvData, jobsList = recruitmentJobsData) {
  if (!cvData) return [];

  const cvLocation = (cvData.location || cvData.province || '').toLowerCase();
  const cvIndustry = (cvData.industry || '').toLowerCase();
  const cvSkills = (cvData.skills || []).map(s => s.toLowerCase());
  const cvHeadline = (cvData.headline || cvData.title || '').toLowerCase();
  const lifePath = cvData.lifePathNumber || 7;

  const scored = jobsList.map(job => {
    let score = 50; // Base score
    const reasons = [];

    // 1. Location match (Max +25 pts)
    const jobLoc = (job.location || job.province || '').toLowerCase();
    const jobProv = (job.province || '').toLowerCase();

    if (cvLocation && (jobLoc.includes(cvLocation) || cvLocation.includes(jobProv) || jobProv.includes(cvLocation))) {
      score += 25;
      reasons.push(`Trùng khớp 100% địa điểm làm việc tại ${job.province || job.location}`);
    } else if (
      (cvLocation.includes('bắc ninh') && jobLoc.includes('hà nội')) ||
      (cvLocation.includes('hồ chí minh') && (jobLoc.includes('bình dương') || jobLoc.includes('đồng nai'))) ||
      (cvLocation.includes('bình dương') && jobLoc.includes('hồ chí minh'))
    ) {
      score += 18;
      reasons.push(`Vị trí lân cận thuận tiện di chuyển (${job.province})`);
    }

    // 2. Industry & Role match (Max +15 pts)
    const jobInd = (job.industry || '').toLowerCase();
    const jobTitle = (job.title || '').toLowerCase();

    if (cvIndustry && (jobInd.includes(cvIndustry) || cvIndustry.includes(jobInd))) {
      score += 10;
    }
    if (cvHeadline) {
      const headlineTokens = cvHeadline.split(/\s+/).filter(t => t.length > 2);
      const matchingTokens = headlineTokens.filter(tok => jobTitle.includes(tok));
      if (matchingTokens.length >= 2) {
        score += 8;
        reasons.push(`Chuyên môn "${cvData.headline || cvData.title}" khớp chuẩn vị trí tuyển dụng`);
      }
    }

    // 3. Skills match (Max +12 pts)
    const jobTags = (job.tags || []).map(t => t.toLowerCase());
    let skillHits = 0;
    cvSkills.forEach(sk => {
      if (jobTags.some(t => t.includes(sk) || sk.includes(t)) || job.description?.toLowerCase().includes(sk)) {
        skillHits++;
      }
    });
    if (skillHits > 0) {
      score += Math.min(12, skillHits * 4);
      reasons.push(`Khớp ${skillHits} kỹ năng kỹ thuật yêu cầu`);
    }

    // 4. Numerology match (Max +10 pts)
    const ideal = job.idealNumbers || [];
    if (ideal.includes(lifePath)) {
      score += 10;
      reasons.push(`Số chủ đạo ${lifePath} cực kỳ tương thích với năng lượng vị trí (${job.numerologyHint || ''})`);
    } else if (Math.abs(ideal[0] - lifePath) === 1 || Math.abs(ideal[0] - lifePath) === 2) {
      score += 5;
    }

    // Cap score at 99%
    const finalScore = Math.min(99, Math.max(65, Math.round(score)));

    return {
      job,
      matchScore: finalScore,
      reasons: reasons.length > 0 ? reasons : [`Tương thích chuyên môn ngành ${job.industry}`, `Độ phù hợp Thần số học số ${lifePath}`]
    };
  });

  // Sort descending by match score
  return scored.sort((a, b) => b.matchScore - a.matchScore);
}

// Matching Algorithm: Match Candidates for Factory Job Posting
export function matchCandidatesForJob(jobData, candidatesList = recruitmentCandidatesData) {
  if (!jobData) return [];

  const jobLocation = (jobData.location || jobData.province || '').toLowerCase();
  const jobProvince = (jobData.province || '').toLowerCase();
  const jobIndustry = (jobData.industry || '').toLowerCase();
  const jobTitle = (jobData.title || '').toLowerCase();
  const jobSkills = (jobData.requiredSkills || jobData.tags || []).map(s => s.toLowerCase());
  const preferredNumber = jobData.preferredLifePath || (jobData.idealNumbers && jobData.idealNumbers[0]) || 4;

  const scored = candidatesList.map(cand => {
    let score = 52; // Base score
    const reasons = [];

    // 1. Location match (Max +24 pts)
    const candLoc = (cand.location || cand.province || '').toLowerCase();
    const candProv = (cand.province || '').toLowerCase();

    if (jobProvince && (candLoc.includes(jobProvince) || candProv.includes(jobProvince))) {
      score += 24;
      reasons.push(`Ứng viên đang sinh sống & sẵn sàng làm việc tại ${cand.province || cand.location}`);
    } else if (
      (jobProvince.includes('bắc ninh') && candLoc.includes('hà nội')) ||
      (jobProvince.includes('đồng nai') && candLoc.includes('hồ chí minh')) ||
      (jobProvince.includes('bình dương') && candLoc.includes('hồ chí minh'))
    ) {
      score += 16;
      reasons.push(`Khoảng cách di chuyển gần (${cand.province})`);
    }

    // 2. Role & Industry match (Max +14 pts)
    const candHead = (cand.headline || '').toLowerCase();
    const candInd = (cand.industry || '').toLowerCase();

    if (jobIndustry && (candInd.includes(jobIndustry) || jobIndustry.includes(candInd))) {
      score += 8;
    }
    const titleTokens = jobTitle.split(/\s+/).filter(t => t.length > 2);
    const hits = titleTokens.filter(tok => candHead.includes(tok));
    if (hits.length >= 2) {
      score += 8;
      reasons.push(`Hồ sơ chuyên môn "${cand.headline}" đúng tiêu chuẩn tìm kiếm`);
    }

    // 3. Skills match (Max +12 pts)
    const candSkills = (cand.skills || cand.tags || []).map(s => s.toLowerCase());
    let skillMatches = 0;
    jobSkills.forEach(js => {
      if (candSkills.some(cs => cs.includes(js) || js.includes(cs)) || cand.summary?.toLowerCase().includes(js)) {
        skillMatches++;
      }
    });
    if (skillMatches > 0) {
      score += Math.min(12, skillMatches * 4);
      reasons.push(`Ứng viên đáp ứng ${skillMatches} kỹ năng then chốt của nhà máy`);
    }

    // 4. Numerology match (Max +10 pts)
    if (cand.lifePathNumber === preferredNumber || (jobData.idealNumbers || []).includes(cand.lifePathNumber)) {
      score += 10;
      reasons.push(`Con số chủ đạo ${cand.lifePathNumber} thuộc nhóm tính cách vàng mà nhà máy đang tìm kiếm`);
    }

    // Cap score at 99%
    const finalScore = Math.min(99, Math.max(68, Math.round(score)));

    return {
      candidate: cand,
      matchScore: finalScore,
      reasons: reasons.length > 0 ? reasons : [`Kinh nghiệm ${cand.experience}`, `Năng lực ${cand.numerologyTitle}`]
    };
  });

  // Sort descending by match score
  return scored.sort((a, b) => b.matchScore - a.matchScore);
}

